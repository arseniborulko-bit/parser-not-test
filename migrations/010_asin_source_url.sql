-- Исходная ссылка на товар в справочнике ASIN.
--
-- До сих пор ссылка нигде не хранилась: в базе оставался только ASIN, а ссылка собиралась на лету
-- из ASIN и страны. Из-за этого терялось всё, чем ссылка отличалась от канонической — параметры,
-- вариант товара, метка продавца. Эталонный справочник (лист structure) состоит именно из ссылок,
-- и задача требует сохранять исходную.
--
-- Пустая строка означает «ссылки не было»: тогда интерфейс по-прежнему показывает собранную из
-- ASIN. Аддитивная миграция, существующие строки не трогает, повторный запуск безопасен.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

DO $$
BEGIN
    IF to_regclass('bsr_radar.asins') IS NULL THEN
        RAISE NOTICE 'Справочника bsr_radar.asins нет (миграция 008 не применялась) — пропуск.';
        RETURN;
    END IF;

    ALTER TABLE bsr_radar.asins ADD COLUMN IF NOT EXISTS source_url TEXT NOT NULL DEFAULT '';
END
$$;

COMMIT;
