"""Адрес доставки для запросов к ScrapingDog: почтовый индекс по домену Amazon.

Amazon показывает цену, наличие и выбранный вариант товара (а с ними и BSR на странице) для адреса доставки.
Без индекса ScrapingDog получает страницу для случайного адреса, поэтому BSR и цена между запросами «прыгают»
и не совпадают с тем, что видит команда. Владелец 16.10.2026: передавать postal_code во всех запросах, для всех
стран; для DE — 10115 (Берлин), как в браузере команды («Liefern nach 10115 Berlin»).

Индексы остальных стран — центр столицы или крупнейшего города; если команда смотрит Amazon с другим адресом,
поменять здесь, чтобы сбор и браузер совпадали.
"""

from __future__ import annotations

from typing import Dict

POSTAL_CODE_BY_DOMAIN: Dict[str, str] = {
    "com": "10001",       # US — Нью-Йорк
    "ca": "M5V 3L9",      # CA — Торонто
    "co.uk": "EC1A 1BB",  # UK — Лондон
    "de": "10115",        # DE — Берлин (как у команды)
    "fr": "75001",        # FR — Париж
    "es": "28001",        # ES — Мадрид
    "it": "00184",        # IT — Рим
    "com.mx": "06000",    # MX — Мехико
    "co.jp": "100-0001",  # JP — Токио
    "com.au": "2000",     # AU — Сидней
}


def location_params(domain: str) -> Dict[str, str]:
    """{"postal_code": …} для домена или пусто, если домен неизвестен (тогда запрос как раньше)."""
    code = POSTAL_CODE_BY_DOMAIN.get(str(domain).strip().lower())
    return {"postal_code": code} if code else {}
